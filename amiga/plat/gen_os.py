for name, base, lvo, ret, args in F:
    regs = {r for _, _, r in args}
    decl = ' '.join(f'register {t} _{n} __asm("{r}") = {n};' for t, n, r in args)
    outs = [f'"+r"(_{n})' for t, n, r in args]
    retexpr = None
    if ret != 'void':
        if 'd0' in regs:
            n0 = [n for t, n, r in args if r == 'd0'][0]; retexpr = f'({ret})_{n0}'
        else:
            decl += f' register {ret} _ret __asm("d0");'; outs.insert(0, '"=r"(_ret)'); retexpr = '_ret'
